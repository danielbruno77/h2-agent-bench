#!/usr/bin/env bash
# PreToolUse (Edit|Write): block edits to files the human owns or the pipeline generates.
# Exit 2 blocks the action; stderr is shown to Claude as feedback.
set -u
INPUT=$(cat)
FILE=$(printf '%s' "$INPUT" | jq -r '.tool_input.file_path // empty')
[ -z "$FILE" ] && exit 0
FILE="${FILE//\\//}"

block() { echo "Blocked: $FILE ($1)" >&2; exit 2; }

case "$FILE" in
  *.env|*.env.*)                     block "secrets are edited by the human only" ;;
  */tasks/*/reference/*)             block "reference artifacts come from the mesh study, not from edits" ;;
  */results/labels.csv)              block "failure labels are hand-written by the human (Day 10 rubric)" ;;
  */results/runs.jsonl|*/results/summary.json) block "generated by results/make_table.py; rerun the script" ;;
  */docs/examples/*.jsonl)           block "recorded traces are immutable evidence" ;;
  */uv.lock)                         block "managed by uv; use 'uv add' or 'uv lock'" ;;
  */hylab/*)                         block "private HyLab material is outside the repo" ;;
  */constant/polyMesh/*)             block "meshes are generated by the mesh tool, never edited" ;;
esac
exit 0
